"""Packs the frames from render-pill-motion.cjs into pillMotionArt.ts: the wake sting (plays once, 2 s),
the listening loop (2.4 s) and one still of the closed mark, as base64 data for the pill page."""
import base64
import glob
import io
import sys

from PIL import Image

frames = sys.argv[1]
out = sys.argv[2]


def pack(name, fps, loop):
    images = [Image.open(f).convert("RGB") for f in sorted(glob.glob(f"{frames}/{name}/f*.png"))]
    buf = io.BytesIO()
    images[0].save(buf, "WEBP", save_all=True, append_images=images[1:], duration=int(1000 / fps), loop=loop,
                   lossless=True, quality=100, method=6)
    return base64.b64encode(buf.getvalue()).decode(), images[0]


sting, _ = pack("sting", 24, 1)
listening, first = pack("listening", 12, 0)
still = io.BytesIO()
first.save(still, "PNG", optimize=True)
open(out, "w").write(
    '/** Generated by scripts/baton/pack-pill-motion.py from the logo kit\'s sting and listening compositions. */\n'
    f'export const STING_WEBP = "{sting}";\n'
    f'export const LISTENING_WEBP = "{listening}";\n'
    f'export const MARK_STILL_PNG = "{base64.b64encode(still.getvalue()).decode()}";\n'
    "/** The ground the motion was rendered on; the pill uses the same so the frames sit in it unseen. */\n"
    'export const MOTION_GROUND = "#0B0B0C";\n'
)
