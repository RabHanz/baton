#!/usr/bin/env node
/* oxlint-disable t3code/namespace-node-imports -- Baton file predating the rule (D82) */
// Writes CHANGELOG.md from the merged pull requests: `node scripts/baton/changelog.mjs [--from-json file]`.
// Needs `gh` signed in unless --from-json is given. Groups by the conventional-commit word at the start of each title.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const GROUPS = [
  ["feat", "Added"],
  ["fix", "Fixed"],
  ["perf", "Faster"],
  ["docs", "Documentation"],
  ["ci", "Build and checks"],
  ["chore", "Maintenance"],
  ["other", "Other"],
];

export const groupOf = (title) => {
  const word = /^([a-z]+)(?:\([^)]*\))?!?:/.exec(title)?.[1];
  return GROUPS.some(([key]) => key === word) ? word : "other";
};

export const render = (prs, repo) => {
  const days = new Map();
  for (const pr of prs.filter((p) => p.baseRefName === "main")) {
    const day = pr.mergedAt.slice(0, 10);
    days.set(day, [...(days.get(day) ?? []), pr]);
  }
  const out = [
    "# Changelog",
    "",
    "Generated by `scripts/baton/changelog.mjs` from the merged pull requests. Newest first.",
    "",
  ];
  for (const day of [...days.keys()].toSorted().toReversed()) {
    out.push(`## ${day}`, "");
    for (const [key, heading] of GROUPS) {
      const rows = days
        .get(day)
        .filter((p) => groupOf(p.title) === key)
        .toSorted((a, b) => b.number - a.number);
      if (rows.length === 0) continue;
      out.push(`### ${heading}`, "");
      for (const p of rows)
        out.push(
          `- ${p.title.replace(/^[a-z]+(?:\([^)]*\))?!?:\s*/, "")} ([#${p.number}](https://github.com/${repo}/pull/${p.number}))`,
        );
      out.push("");
    }
  }
  return out.join("\n");
};

if (import.meta.url === `file://${process.argv[1]}`) {
  const repo = process.env.GITHUB_REPOSITORY ?? "RabHanz/baton";
  const i = process.argv.indexOf("--from-json");
  const json =
    i > 0
      ? readFileSync(process.argv[i + 1], "utf8")
      : execFileSync(
          "gh",
          [
            "pr",
            "list",
            "-R",
            repo,
            "--state",
            "merged",
            "--limit",
            "1000",
            "--json",
            "number,title,mergedAt,baseRefName",
          ],
          { encoding: "utf8" },
        );
  writeFileSync("CHANGELOG.md", render(JSON.parse(json), repo));
}
