"""The wake sting for the window (sidebar at start, About page): the logo kit's transparent animation at 128 px,
one WebP for a dark ground and one for a light one, recoloured from the kit's Damson to Woad.

  python scripts/tessaya/pack-window-motion.py <films> apps/desktop/src/baton/home/windowMotionArt.ts

<films> holds sting-alpha-dark.apng and sting-alpha-light.apng with 90 frames each: the kit's
motion/colour/sting-alpha-<ground>/index.html drawn with draw(t) at t = i * 2 / 89. Played at 30 fps the
2 s film runs 3 s: slower, and every frame is a real one (the kit's 60-frame film would repeat frames).

Dark: paper white (the mark) stays, the Damson dye #BC96CE becomes Woad's #5FB3B3.
Light: the Damson ink #151019 becomes Woad's #0F1B1E and the dye #4A205E becomes #14505A.
Each pixel is placed on the line between the palette's two colours and moved to the new line.
"""
import base64
import io
import sys

from PIL import Image, ImageSequence

folder, out = sys.argv[1], sys.argv[2]
SIZE = 128
FRAMES = 90
FPS = 30


def rgb(h):
    return tuple(int(h[i : i + 2], 16) for i in (1, 3, 5))


def recolour(image, old_base, old_dye, new_base, new_dye):
    ob, od, nb, nd = map(rgb, (old_base, old_dye, new_base, new_dye))
    axis = [d - b for d, b in zip(od, ob)]
    length = sum(a * a for a in axis)
    pixels = []
    for r, g, b, a in image.getdata():
        t = max(0.0, min(1.0, sum((c - p) * x for c, p, x in zip((r, g, b), ob, axis)) / length))
        pixels.append(tuple(round(p + t * (n - p)) for p, n in zip(nb, nd)) + (a,))
    result = Image.new("RGBA", image.size)
    result.putdata(pixels)
    return result


def pack(ground, old_base, old_dye, new_base, new_dye):
    image = Image.open(f"{folder}/sting-alpha-{ground}.apng")
    frames = [f.convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS) for f in ImageSequence.Iterator(image)]
    step = len(frames) / FRAMES
    picked = [recolour(frames[min(len(frames) - 1, int(i * step))], old_base, old_dye, new_base, new_dye) for i in range(FRAMES)]
    buf = io.BytesIO()
    picked[0].save(buf, "WEBP", save_all=True, append_images=picked[1:], duration=int(1000 / FPS), loop=1,
                   lossless=True, quality=100, method=6, exact=True)
    return base64.b64encode(buf.getvalue()).decode()


dark = pack("dark", "#F3EFEB", "#BC96CE", "#EEEDE4", "#5FB3B3")
light = pack("light", "#151019", "#4A205E", "#0F1B1E", "#14505A")
open(out, "w").write(
    "/** Generated by scripts/tessaya/pack-window-motion.py: the wake sting at 128 px, Woad, for each ground. */\n"
    f'export const WINDOW_STING_DARK =\n  "{dark}";\n'
    f'export const WINDOW_STING_LIGHT =\n  "{light}";\n'
)
